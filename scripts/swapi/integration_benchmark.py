#!/usr/bin/env python3
"""
Two-phase integration accuracy benchmark for the SWAPI proton solar wind integral.

Ground truths are pre-computed fixed-limit integrals loaded from
tests/swapi/l3a/science/reference_integrals.csv (generated by
scripts/swapi/generate_reference_integrals.py).

Phase 1 – Reference sweep: all four dimensions share the same N; find the
minimum N_ref such that every test case is within 1 % of the ground truth.

Phase 2 – Combination optimisation: sweep each dimension independently (others
fixed at N_ref) to get per-dimension error curves, then enumerate all 20^4
combinations via a separable upper-bound estimate (max error ≈ max over dims
of that dim's independent worst-case error).  Find the combination that keeps
every test case within 1 % and minimises N_el × N_az_sg × N_az_oa × N_speed.

Output: docs/swapi/figures/integration_benchmark.png
Usage:  python scripts/swapi/integration_benchmark.py
"""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from imap_l3_processing.constants import METERS_PER_KILOMETER, PROTON_CHARGE_COULOMBS, PROTON_MASS_KG
from imap_l3_processing.swapi.l3a.science.calculate_proton_solar_wind_moments import SWParams
from imap_l3_processing.swapi.l3a.science.speed_calculation import SWAPI_K_FACTOR
from imap_l3_processing.swapi.l3a.science.swapi_response import SWAPIResponse
from tests.swapi.l3a.science.reference_integral import integral as _integral

_REPO_ROOT = Path(__file__).resolve().parents[2]
_INSTRUMENT_DATA = _REPO_ROOT / "instrument_team_data" / "swapi"
_OUTPUT_DIR = _REPO_ROOT / "docs" / "swapi" / "figures"
_REFERENCE_INTEGRALS_PATH = _REPO_ROOT / "tests" / "swapi" / "l3a" / "science" / "reference_integrals.csv"

_ERROR_THRESHOLD = 0.01
_N_SWEEP = np.unique(np.round(np.geomspace(1, 50, 20))).astype(int)
# azimuth_oa is fixed at high N during the N_ref sweep and swept last in phase 2
_N_AZ_OA_FIXED = int(_N_SWEEP[-1])
_DIMS = ["elevation", "azimuth_sg", "speed", "azimuth_oa"]
_DIM_LABELS = {"elevation": "Elevation", "azimuth_sg": "Azimuth (SG)", "azimuth_oa": "Azimuth (OA)", "speed": "Speed"}
# positional order expected by _integral(grid, sw, n_el, n_az_sg, n_az_oa, n_sp)
_INTEGRAL_DIM_ORDER = ["elevation", "azimuth_sg", "azimuth_oa", "speed"]


def main():
    print("Loading calibration data...")
    swapi_response = SWAPIResponse.from_files(
        _INSTRUMENT_DATA / "imap_swapi_azimuthal_transmission.csv",
        _INSTRUMENT_DATA / "imap_swapi_central_effective_area.csv",
        _INSTRUMENT_DATA / "imap_swapi_passband_fit_coefficients.csv",
    )
    cases, ground_truths = _load_cases_and_truths(swapi_response)
    print(f"Loaded {len(cases)} cases from {_REFERENCE_INTEGRALS_PATH.name}.")

    # Phase 1: find minimum shared N_ref within threshold
    ref_errors = _sweep_nref(cases, ground_truths)
    n_ref = _select_nref(ref_errors)
    k_ref = np.where(_N_SWEEP == n_ref)[0][0]
    print(f"\nSelected N_ref = {n_ref} (max error {ref_errors[:, k_ref].max():.2%})")
    _print_convergence_outliers(ref_errors, cases)

    # Phase 2: per-dimension sweeps then combination optimisation
    per_dim_errors = _sweep_per_dim(cases, ground_truths, n_ref)
    ns_opt, estimated_error = _optimize_combination(per_dim_errors)
    print(f"\nOptimal N: {dict(zip(_DIMS, ns_opt))}  (estimated max error {estimated_error:.2%})")

    _plot(ref_errors, n_ref, per_dim_errors, ns_opt, cases)


# ── Case helpers ──────────────────────────────────────────────────────────────

def _load_cases_and_truths(swapi_response):
    """Load pre-computed ground-truth integrals and reconstruct (temp_ev, grid, sw) cases."""
    df = pd.read_csv(_REFERENCE_INTEGRALS_PATH)
    cases = []
    for _, row in df.iterrows():
        grid = swapi_response.create_passband_grid(_peak_voltage(row['bulk_speed']))
        sw = _make_sw_params(row['bulk_speed'], row['temperature_ev'],
                             row['bulk_azimuth'], row['bulk_elevation'], row['density'])
        cases.append((row['temperature_ev'], grid, sw))
    return cases, df['integral'].tolist()


def _print_convergence_outliers(ref_errors, cases, n_show=10):
    """Print SW params for the cases that require the most N points to converge."""
    # For each case find the index of the first N where error drops below threshold
    converge_k = np.argmax(ref_errors <= _ERROR_THRESHOLD, axis=1)
    # argmax returns 0 when never True; mark those as the last index
    never_converged = (ref_errors <= _ERROR_THRESHOLD).sum(axis=1) == 0
    converge_k[never_converged] = len(_N_SWEEP) - 1
    converge_n = _N_SWEEP[converge_k]

    order = np.argsort(converge_n)[::-1][:n_show]
    print(f"\nTop {n_show} slowest-converging cases (N needed to reach {_ERROR_THRESHOLD:.0%}):")
    header = f"  {'N_conv':>6}  {'speed':>7}  {'temp_eV':>8}  {'azimuth':>8}  {'elevation':>10}  {'density':>8}  {'err@N_conv':>10}"
    print(header)
    for i in order:
        _, _, sw = cases[i]
        err = ref_errors[i, converge_k[i]]
        temp_ev = PROTON_MASS_KG * (sw.thermal_speed * METERS_PER_KILOMETER) ** 2 / PROTON_CHARGE_COULOMBS
        print(f"  {converge_n[i]:>6}  {sw.bulk_speed:>7.1f}  {temp_ev:>8.2f}"
              f"  {sw.bulk_azimuth:>8.2f}  {sw.bulk_elevation:>10.2f}  {sw.density:>8.2f}  {err:>10.2%}")


# ── Phase 1 ───────────────────────────────────────────────────────────────────

def _sweep_nref(cases, ground_truths):
    """For each N in _N_SWEEP, compute relative error with elevation, az_sg, and speed = N.
    azimuth_oa is fixed at _N_AZ_OA_FIXED throughout.
    Returns array shape (n_cases, len(_N_SWEEP))."""
    n_cases = len(cases)
    errors = np.empty((n_cases, len(_N_SWEEP)))
    for k, n in enumerate(_N_SWEEP):
        print(f"  N_ref sweep: N={n}", flush=True)
        for i, ((_temp, grid, sw), truth) in enumerate(zip(cases, ground_truths)):
            val = _integral(grid, sw, n, n, _N_AZ_OA_FIXED, n)
            errors[i, k] = abs(val - truth) / max(1e4, abs(truth))
    return errors


def _select_nref(ref_errors):
    """Smallest N in _N_SWEEP where the max error across all cases is ≤ threshold."""
    for k, n in enumerate(_N_SWEEP):
        if ref_errors[:, k].max() <= _ERROR_THRESHOLD:
            return int(n)
    return int(_N_SWEEP[-1])


# ── Phase 2 ───────────────────────────────────────────────────────────────────

def _sweep_per_dim(cases, ground_truths, n_ref):
    """Sweep each dimension independently; others fixed at n_ref, except azimuth_oa
    which stays at _N_AZ_OA_FIXED when it is not the swept dim.
    Returns dict dim -> array(n_cases, len(_N_SWEEP))."""
    per_dim_errors = {}
    for dim in _DIMS:
        errors = np.empty((len(cases), len(_N_SWEEP)))
        for k, n in enumerate(_N_SWEEP):
            ns = {d: (n if d == dim else (_N_AZ_OA_FIXED if d == "azimuth_oa" else n_ref))
                  for d in _DIMS}
            ns_trial = [ns[d] for d in _INTEGRAL_DIM_ORDER]
            print(f"  Per-dim sweep: {dim} N={n}", flush=True)
            for i, ((_temp, grid, sw), truth) in enumerate(zip(cases, ground_truths)):
                val = _integral(grid, sw, *ns_trial)
                errors[i, k] = abs(val - truth) / abs(truth)
        per_dim_errors[dim] = errors
    return per_dim_errors


def _optimize_combination(per_dim_errors):
    """Enumerate all N_SWEEP^4 combinations via separable upper-bound estimate.

    For each combo the estimated max error is the maximum over dimensions of
    that dimension's worst-case independent error.  Returns (ns_tuple, error).
    """
    # worst-case error per dim per sweep point: shape (4, K)
    dim_max = np.array([per_dim_errors[d].max(axis=0) for d in _DIMS])  # (4, K)
    K = len(_N_SWEEP)
    k = np.arange(K)
    k0, k1, k2, k3 = np.meshgrid(k, k, k, k, indexing='ij')

    combo_error = np.maximum.reduce([
        dim_max[0][k0], dim_max[1][k1], dim_max[2][k2], dim_max[3][k3],
    ])
    combo_product = (
        _N_SWEEP[k0].astype(np.int64) * _N_SWEEP[k1]
        * _N_SWEEP[k2] * _N_SWEEP[k3]
    )
    combo_product[combo_error > _ERROR_THRESHOLD] = np.iinfo(np.int64).max

    idx = np.unravel_index(np.argmin(combo_product), combo_product.shape)
    ns_opt = tuple(int(_N_SWEEP[ki]) for ki in idx)
    return ns_opt, float(combo_error[idx])


# ── Plotting ──────────────────────────────────────────────────────────────────

def _plot(ref_errors, n_ref, per_dim_errors, ns_opt, cases):
    temperatures = np.array([t for t, _g, _s in cases])
    log_t = np.log10(temperatures)
    t_norm = matplotlib.colors.Normalize(vmin=log_t.min(), vmax=log_t.max())
    cmap = matplotlib.colormaps["plasma"]
    colors = cmap(t_norm(log_t))

    fig, axes = plt.subplots(1, 5, figsize=(20, 4), sharey=True)

    def _draw(ax, errors, vline, vline_label, title):
        for i in range(len(cases)):
            ax.semilogy(_N_SWEEP, errors[i], color=colors[i], linewidth=0.6, alpha=0.7)
        ax.axhline(_ERROR_THRESHOLD, color="crimson", linestyle="--", linewidth=1.2, label="1% threshold")
        ax.axvline(vline, color="gray", linestyle=":", linewidth=1.2, label=vline_label)
        ax.set_title(title)
        ax.set_xlabel("N")
        ax.grid(True, which="both", alpha=0.3)

    _draw(axes[0], ref_errors, n_ref, f"N_ref={n_ref}",
          f"N_ref sweep\n(az_oa fixed at {_N_AZ_OA_FIXED})")
    axes[0].set_ylabel("Relative error")

    for ax, dim, n_opt in zip(axes[1:], _DIMS, ns_opt):
        _draw(ax, per_dim_errors[dim], n_opt, f"N_opt={n_opt}",
              f"{_DIM_LABELS[dim]}\n(others at N_ref={n_ref})")

    handles, lbls = axes[0].get_legend_handles_labels()
    fig.legend(handles, lbls, loc="lower left", fontsize=8, bbox_to_anchor=(0.01, -0.06))

    sm = matplotlib.cm.ScalarMappable(cmap=cmap, norm=t_norm)
    sm.set_array([])
    cbar = fig.colorbar(sm, ax=axes, orientation="vertical", fraction=0.015, pad=0.01)
    cbar.set_label("Temperature (eV)")
    cbar.set_ticks([np.log10(t) for t in [1, 3, 10, 30, 100]])
    cbar.set_ticklabels(["1", "3", "10", "30", "100"])

    product = int(np.prod(ns_opt))
    fig.suptitle(
        f"Optimal combination: {dict(zip(_DIMS, ns_opt))}  "
        f"(product={product},  {len(cases)} random conditions)",
        fontsize=10,
    )
    fig.tight_layout()

    _OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    out = _OUTPUT_DIR / "integration_benchmark.png"
    fig.savefig(out, dpi=150, bbox_inches="tight")
    print(f"\nSaved {out}")


# ── Utilities ─────────────────────────────────────────────────────────────────

def _peak_voltage(bulk_speed_km_s):
    return (PROTON_MASS_KG * (bulk_speed_km_s * METERS_PER_KILOMETER) ** 2
            / (2 * SWAPI_K_FACTOR * PROTON_CHARGE_COULOMBS))


def _make_sw_params(bulk_speed, temperature_ev, bulk_azimuth, bulk_elevation, density=5.0):
    thermal_speed = float(np.sqrt(temperature_ev * PROTON_CHARGE_COULOMBS / PROTON_MASS_KG)
                          / METERS_PER_KILOMETER)
    return SWParams(density=density, bulk_speed=bulk_speed, bulk_azimuth=bulk_azimuth,
                    bulk_elevation=bulk_elevation, thermal_speed=thermal_speed)


if __name__ == "__main__":
    main()
